
//       LEFT SHIFT

// 5<<1 iska matlab 5 ko ek baar left shift karo

// 5 = 0000 0000 0......... 0101
// then left shift is
//   = 0000 0000 0..........1010  ==> 10

//   Means single left shift mai number two times hoga..(in majority cases, not for very big no.)
//   if 2 times left shift then 4 se multiply
//   if 3 times left shift then 8 se multiply



//        RIGHT SHIFT

// 5>>2  iska matlab 5 ko 2 baar right shift karo

// 5 = 0000 0000 0......... 0101
// then right shift is
//   = 0000 0000 0..........0001  ==> 1

//   Means single right shift mai number two se divide hoga..(in majority cases, not for very big no.)
// 5/2 = 2
// 2/2 = 1